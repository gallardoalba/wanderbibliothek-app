package org.wanderbibliothek.app.ui

import java.util.Locale

/**
 * Textos de la interfaz en alemán y castellano.
 *
 * La plataforma tiene el alemán como idioma por defecto y el castellano como
 * alternativa; la app repite esa regla. Se guardan en memoria en vez de en
 * `strings.xml` porque el idioma se cambia desde Ajustes sin reiniciar la
 * actividad y porque el diccionario se puede probar en la JVM (ver
 * `TextsTest`): si falta una clave, la prueba falla antes de compilar.
 */
class Texts(private val values: Map<String, String>) {
    operator fun get(key: String): String = values[key] ?: key

    /** Sustituye `%1\$s`, `%2$d`… con los argumentos indicados. */
    fun format(key: String, vararg args: Any): String {
        val template = get(key)
        return try {
            String.format(Locale.ROOT, template, *args)
        } catch (_: java.util.IllegalFormatException) {
            // Un especificador que no encaja con el argumento (por ejemplo `%d`
            // con un número ya formateado) no debe tumbar la pantalla: se
            // degrada a texto y se sigue pintando.
            String.format(
                Locale.ROOT,
                template.replace(Regex("%(\\d+)\\$[dsf]"), "%${'$'}1\\${'$'}s"),
                *args,
            )
        }
    }

    val keys: Set<String> get() = values.keys
}

